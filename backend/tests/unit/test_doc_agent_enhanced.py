class TestConfidenceCalculation:
    """Tests for confidence calculation"""

    def test_calculate_confidence_multiple_suggestions(self, doc_agent_config):
        """Test confidence with multiple suggestions"""
        agent = DocAgent(config=doc_agent_config)
        suggestions = [
            Suggestion(
                id="1",
                code="code1",
                description="desc1",
                confidence=ConfidenceLevel.HIGH,
            ),
            Suggestion(
                id="2",
                code="code2",
                description="desc2",
                confidence=ConfidenceLevel.MEDIUM,
            ),
        ]
        confidence = agent._calculate_confidence(suggestions)
        assert isinstance(confidence, float)
        assert 0.0 <= confidence <= 1.0
        # Should be average: (0.9 + 0.7) / 2 = 0.8
        assert confidence == pytest.approx(0.8, abs=0.01)

